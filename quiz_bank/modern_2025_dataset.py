def _load_content_index(path: Path = DEFAULT_CITY_PERIOD_CONTENT_PATH) -> dict[str, dict[str, object]]:
    items = json.loads(Path(path).read_text(encoding="utf-8"))
    return {
        str(item["city"]): item
        for item in items
        if item.get("period_code") == PERIOD_CODE
    }


def _sanitize_city_reference(city: str, text: str) -> str:
    value = str(text or "").strip()
    if not value:
        return value
    value = re.sub(re.escape(city), "этот город", value, flags=re.IGNORECASE)
    value = re.sub(r"\s+", " ", value).strip()
    return value


def _first_sentence(text: str) -> str:
    value = str(text or "").strip()
    if not value:
        return value
    parts = re.split(r"(?<=[.!?])\s+", value, maxsplit=1)
    return parts[0].strip()


def _build_profiles() -> list[dict[str, str]]:
    content_index = _load_content_index()
    profiles: list[dict[str, str]] = []

    for city, metadata in MODERN_2025_METADATA.items():
        content = content_index[city]
        profiles.append(
            {
                "city": city,
                "display_name_2025": str(content["display_name"]),
                "subtitle_fact": _sanitize_city_reference(city, str(content["subtitle"])),
                "short_description_fact": _sanitize_city_reference(
                    city,
                    str(content["short_description"]),
                ),
                "history_summary_fact": _sanitize_city_reference(
                    city,
                    _first_sentence(str(content["history_summary"])),
                ),
                "interesting_fact_fact": _sanitize_city_reference(
                    city,
                    str(content["interesting_fact"]),
                ),
                "importance_reason_fact": _sanitize_city_reference(
                    city,
                    str(content.get("importance_reason") or content["short_description"]),
                ),
                **metadata,
            }
        )

    return profiles


MODERN_2025_PROFILES = _build_profiles()
MODERN_2025_CITIES = tuple(profile["city"] for profile in MODERN_2025_PROFILES)


def _pick_distractors(
    city: str,
    field_name: str,
    answer: str,
    profiles: list[dict[str, str]],
    count: int = 3,
) -> list[str]:
    unique_values: list[str] = []
    seen: set[str] = set()

    for profile in profiles:
        if profile["city"] == city:
            continue
        candidate = _sanitize_city_reference(profile["city"], str(profile[field_name]))
        if not candidate or candidate == answer or candidate in seen:
            continue
        seen.add(candidate)
        unique_values.append(candidate)

    if len(unique_values) < count:
        raise ValueError(
            f"Недостаточно уникальных distractors для {city}/{field_name}: найдено {len(unique_values)}."
        )

    randomizer = random.Random(f"{PERIOD_CODE}|{city}|{field_name}")
    return randomizer.sample(unique_values, count)


def _build_field_question(
    profile: dict[str, str],
    profiles: list[dict[str, str]],
    field_name: str,
    question: str,
    fact: str,
) -> dict[str, object]:
    answer = _sanitize_city_reference(profile["city"], str(profile[field_name]))
    distractors = _pick_distractors(profile["city"], field_name, answer, profiles)
    return {
        "question": question,
        "correct": answer,
        "distractors": distractors,
        "fact": _sanitize_city_reference(profile["city"], fact),
    }


