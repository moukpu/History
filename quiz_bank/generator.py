def _deterministic_options(question: str, correct: str, candidates: list[str]) -> list[str]:
    normalized_correct = normalize_text(correct)
    unique_candidates: list[str] = []
    seen = set()
    for candidate in candidates:
        normalized_candidate = normalize_text(candidate)
        if normalized_candidate == normalized_correct or normalized_candidate in seen:
            continue
        seen.add(normalized_candidate)
        unique_candidates.append(candidate)

    if len(unique_candidates) < 3:
        raise ValueError(f"Not enough distractors for question: {question}")

    randomizer = random.Random(f"{question}|{correct}")
    distractors = randomizer.sample(unique_candidates, 3)
    options = [correct, *distractors]
    randomizer.shuffle(options)
    return options


def from_pool(city: str, question: str, correct: str, pool: list[str], fact: str) -> QuizDraft:
    return QuizDraft(
        city=city,
        question=question,
        correct_answer=correct,
        options=_deterministic_options(question, correct, pool),
        fact=fact,
    )


def from_options(
    city: str,
    question: str,
    correct: str,
    distractors: list[str],
    fact: str,
) -> QuizDraft:
    return QuizDraft(
        city=city,
        question=question,
        correct_answer=correct,
        options=_deterministic_options(question, correct, distractors),
        fact=fact,
    )


def city_answer(city: str, question: str, fact: str) -> QuizDraft:
    return QuizDraft(
        city=city,
        question=question,
        correct_answer=city,
        options=_deterministic_options(question, city, APPROVED_CITIES),
        fact=fact,
    )


def true_statement(
    city: str,
    question: str,
    correct_statement: str,
    false_statements: list[str],
    fact: str,
) -> QuizDraft:
    return from_options(city, question, correct_statement, false_statements, fact)


