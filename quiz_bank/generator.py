def generate_quiz_bank() -> list[dict[str, object]]:
    drafts_by_city = _build_city_drafts()
    all_records: list[dict[str, object]] = []

    missing_cities = [city for city in APPROVED_CITIES if city not in drafts_by_city]
    if missing_cities:
        raise ValueError(
            "Generator does not contain all approved cities: "
            + ", ".join(missing_cities)
        )

    for city, drafts in drafts_by_city.items():
        if len(drafts) != CITY_QUESTION_TARGET:
            raise ValueError(
                f"City '{city}' must contain exactly {CITY_QUESTION_TARGET} drafts, "
                f"got {len(drafts)}."
            )
        all_records.extend(draft.to_record() for draft in drafts)

    return all_records


def export_quiz_bank(path: Path | str = DEFAULT_DATA_PATH) -> Path:
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    records = generate_quiz_bank()
    destination.write_text(
        json.dumps(records, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    return destination
